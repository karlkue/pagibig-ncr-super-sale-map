def get_coords(name: str, city: str, offset_idx: int = 0) -> tuple[float, float]:
    for key, (lat, lng) in BUILDING_COORDS.items():
        if key.lower() in name.lower():
            # Tiny deterministic jitter (~15m) so multiple units in the same building don't overlap identically
            jitter_lat = ((offset_idx % 7) - 3) * 0.00012
            jitter_lng = (((offset_idx // 7) % 7) - 3) * 0.00012
            return round(lat + jitter_lat, 5), round(lng + jitter_lng, 5)
