def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    data_dir = repo_root / "data"
    data_dir.mkdir(parents=True, exist_ok=True)

    for idx, rec in enumerate(REAL_RECORDS):
        lat, lng = get_coords(rec["property_name"], rec["city"], idx)
        rec["lat"] = lat
        rec["lng"] = lng
        rec["portal_url"] = rec["source_url"]
        rec["notes"] = f"Verified from {rec['source_page']}. Title: {rec['title_no']}."

    condos_path = data_dir / "ropa_condos.json"
    condos_path.write_text(json.dumps(REAL_RECORDS, indent=2, ensure_ascii=False), encoding="utf-8")

    dir_path = data_dir / "banks_directory.json"
    dir_path.write_text(json.dumps(BANKS_DIRECTORY, indent=2, ensure_ascii=False), encoding="utf-8")

    print(f"Wrote {len(REAL_RECORDS)} real, verified NCR Green-Tag condos to {condos_path}")
    print(f"Wrote {len(BANKS_DIRECTORY)} bank ROPA portals/PDF sources to {dir_path}")


if __name__ == "__main__":
    main()
